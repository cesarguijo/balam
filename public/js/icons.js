/**
 * A valid icon name, such as 'user' or 'lock'. Names describe the drawing,
 * not what it is used for.
 * @typedef {keyof typeof icons} IconName
 */

/**
 * Returns the SVG of the given icon, ready to be inserted in a template.
 * @param {IconName} name - The icon name.
 * @returns {string} The icon's SVG markup.
 * @throws {RangeError} If there is no icon with that name.
 */
export function icon(name) {
  checkIconName(name);

  return /* HTML */ `<svg
    class="icon"
    aria-hidden="true"
    viewBox="0 0 24 24"
    fill="none"
    stroke="currentColor"
    stroke-width="2"
    stroke-linecap="round"
    stroke-linejoin="round"
  >
    ${icons[name]}
  </svg>`;
}

/**
 * Tells whether an icon with that name exists. Useful for names that come
 * from outside the code, such as an HTML attribute.
 * @param {string} name - The icon name.
 * @returns {boolean} `true` if the icon exists.
 */
export function isAnIcon(name) {
  return iconNames.includes(name);
}

/**
 * Stops with an error if the icon does not exist, so a misspelled name
 * fails loudly instead of drawing an empty icon.
 * @param {string} name - The icon name.
 * @throws {RangeError} If there is no icon with that name.
 */
export function checkIconName(name) {
  if (!isAnIcon(name)) {
    throw new RangeError(`Icon ${name} does not exist`);
  }
}

